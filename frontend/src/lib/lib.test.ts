describe('formatting', () => {
  it('formats clock times', () => {
    expect(formatClock(0)).toBe('0:00');
    expect(formatClock(59.9)).toBe('0:59');
    expect(formatClock(75)).toBe('1:15');
    expect(formatClock(3725)).toBe('1:02:05');
    expect(formatClock(-5)).toBe('0:00');
  });

  it('formats subtitle timestamps with millisecond precision', () => {
    expect(formatSubtitleTime(4.22, ',')).toBe('00:00:04,220');
    expect(formatSubtitleTime(3725.5, '.')).toBe('01:02:05.500');
    expect(formatSubtitleTime(0.0004, ',')).toBe('00:00:00,000');
    // Rounding up must carry into the seconds, never print 1000 ms.
    expect(formatSubtitleTime(59.9996, '.')).toBe('00:01:00.000');
  });

  it('formats durations, reading time, numbers and percentages', () => {
    expect(formatDuration(45)).toBe('45 s');
    expect(formatDuration(1120)).toBe('18 min 40 s');
    expect(formatDuration(3600)).toBe('1 h');
    expect(formatDuration(7260)).toBe('2 h 1 min');
    expect(formatReadingTime(0.4)).toBe('< 1 min');
    expect(formatReadingTime(14.6)).toBe('15 min');
    expect(formatReadingTime(125)).toBe('2 h 5 min');
    expect(formatNumber(3357)).toBe('3,357');
    expect(formatCompact(9999)).toBe('9,999');
    expect(formatCompact(25300837)).toBe('25.3M');
    expect(formatPercent(0.246)).toBe('25%');
  });

  it('links to a moment in the video', () => {
    expect(youtubeTimeUrl('aircAruvnKk', 75.9)).toBe('https://www.youtube.com/watch?v=aircAruvnKk&t=75s');
  });
});

describe('checkYouTubeUrl', () => {
  it.each([
    'https://www.youtube.com/watch?v=dQw4w9WgXcQ',
    'https://youtu.be/dQw4w9WgXcQ?t=10',
    'https://www.youtube.com/shorts/dQw4w9WgXcQ',
    'https://m.youtube.com/watch?v=dQw4w9WgXcQ&list=PL123',
    'youtube.com/embed/dQw4w9WgXcQ',
    'dQw4w9WgXcQ',
  ])('accepts %s', (url) => {
    expect(checkYouTubeUrl(url)).toEqual({ ok: true, videoId: 'dQw4w9WgXcQ' });
  });

  it.each([
    ['', /Paste a YouTube link/],
    ['hello there', /doesn't look like a link/],
    ['https://vimeo.com/123', /Only YouTube links/],
    ['https://www.youtube.com/playlist?list=PL123', /playlist/],
    ['https://www.youtube.com/@channel', /channel/],
    ['https://www.youtube.com/watch?v=abc', /isn't valid/],
    ['https://youtu.be/', /missing its video id/],
    ['https://www.youtube.com/feed/trending', /doesn't point to a YouTube video/],
  ])('rejects %j with a helpful message', (url, message) => {
    const check = checkYouTubeUrl(url);
    expect(check.ok).toBe(false);
    if (!check.ok) expect(check.message).toMatch(message);
  });
});

describe('exporters', () => {
  it('writes SubRip with numbered cues and comma milliseconds', () => {
    expect(toSrt(result.transcript.cues)).toBe(
      ['1', '00:00:04,220 --> 00:00:05,400', 'This is a 3.', '', '2', '00:00:06,060 --> 01:02:05,500', 'Tom & Jerry <3 --> the end', ''].join('\n'),
    );
  });

  it('writes WebVTT with a header, dot milliseconds and escaped cue text', () => {
    expect(toVtt(result.transcript.cues)).toBe(
      ['WEBVTT', '', '00:00:04.220 --> 00:00:05.400', 'This is a 3.', '', '00:00:06.060 --> 01:02:05.500', 'Tom &amp; Jerry &lt;3 --&gt; the end', ''].join('\n'),
    );
  });

  it('writes the transcript as text with section headings and optional timestamps', () => {
    const withTimes = toTranscriptText(result, { timestamps: true });
    expect(withTimes).toContain('But what is a neural network? | Chapter 1');
    expect(withTimes).toContain('Channel:   3Blue1Brown');
    expect(withTimes).toContain('Duration:  18 min 40 s');
    expect(withTimes).toContain('## Introduction (0:00)');
    expect(withTimes).toContain('[0:04] This is a 3. It is sloppily written.');
    expect(withTimes).toContain('## Series preview (1:07)');
    expect(withTimes.endsWith('living under a rock.\n')).toBe(true);

    const plain = toTranscriptText(result, { timestamps: false });
    expect(plain).toContain('\nThis is a 3. It is sloppily written.\n');
    expect(plain).not.toContain('[0:04]');
  });

  it('writes the summary as text, skipping sections without points', () => {
    const text = toSummaryText(result);
    expect(text).toContain('SUMMARY\n\nA neural network recognises digits.');
    expect(text).toContain('KEY TAKEAWAYS\n\n  • [4:33] Layers build on each other.');
    expect(text).toContain('Introduction (0:00 – 1:07)\n  • [0:04] This is a 3.');
    expect(text).not.toContain('Series preview');
    expect(text).toContain('KEYWORDS\n\nneural network, layer');
  });

  it('writes captions one per line', () => {
    expect(toCueText(result.transcript.cues, { timestamps: true })).toBe('[0:04] This is a 3.\n[0:06] Tom & Jerry <3 --> the end');
    expect(toCueText(result.transcript.cues, { timestamps: false })).toBe('This is a 3.\nTom & Jerry <3 --> the end');
  });

  it('builds filenames that are valid on every platform', () => {
    expect(safeFilename('But what is a neural network? | Chapter 1', 'transcript', 'txt')).toBe('But what is a neural network Chapter 1 - transcript.txt');
    expect(safeFilename('a/b\\c:d*e?"f<g>h|i', 'captions', 'srt')).toBe('a b c d e f g h i - captions.srt');
    expect(safeFilename('   ...   ', 'summary', 'pdf')).toBe('youtube-video - summary.pdf');
    expect(safeFilename('हिन्दी वीडियो', 'transcript', 'txt')).toBe('हिन्दी वीडियो - transcript.txt');
    expect(safeFilename('x'.repeat(300), 'summary', 'txt').length).toBeLessThanOrEqual(80 + ' - summary.txt'.length);
  });
});

describe('speech helpers', () => {
  it('splits text into short chunks at sentence ends without losing words', async () => {
    const { splitForSpeech } = await import('./speech');
    const sentence = 'The network learns to recognise digits from thousands of labelled examples.';
    const text = Array.from({ length: 12 }, () => sentence).join(' ');
    const chunks = splitForSpeech(text);
    expect(chunks.length).toBeGreaterThan(3);
    expect(chunks.every((chunk) => chunk.length <= 220)).toBe(true);
    expect(chunks.every((chunk) => chunk.endsWith('.'))).toBe(true);
    expect(chunks.join(' ')).toBe(text);
  });

  it('breaks a sentence with no punctuation at spaces and handles empty text', async () => {
    const { splitForSpeech } = await import('./speech');
    const long = Array.from({ length: 120 }, (_, i) => `word${i}`).join(' ');
    const chunks = splitForSpeech(long);
    expect(chunks.every((chunk) => chunk.length <= 220)).toBe(true);
    expect(chunks.join(' ')).toBe(long);
    expect(splitForSpeech('   ')).toEqual([]);
    expect(splitForSpeech('यह एक वाक्य है। यह दूसरा है।')).toEqual(['यह एक वाक्य है। यह दूसरा है।']);
  });

  it('picks the closest installed voice for a language', async () => {
    const { pickVoice } = await import('./speech');
    const voices = [{ lang: 'en-GB' }, { lang: 'en-US', default: true }, { lang: 'hi-IN' }, { lang: 'pt_BR' }];
    expect(pickVoice(voices, 'en-GB')?.lang).toBe('en-GB');
    expect(pickVoice(voices, 'en')?.lang).toBe('en-US');
    expect(pickVoice(voices, 'hi')?.lang).toBe('hi-IN');
    expect(pickVoice(voices, 'pt-PT')?.lang).toBe('pt_BR');
    expect(pickVoice(voices, 'ja')).toBeNull();
  });
});

describe('joinForSpeech', () => {
  it('joins pieces with single full stops and drops a repeated heading', async () => {
    const { joinForSpeech } = await import('./speech');
    expect(joinForSpeech(['This video is private', 'This video is private. Only public videos work.', undefined, 'Ask the owner.'])).toBe(
      'This video is private. Only public videos work. Ask the owner.',
    );
    expect(joinForSpeech(['Is it done?', 'Yes'])).toBe('Is it done? Yes.');
    expect(joinForSpeech([null, '  '])).toBe('');
  });
});

describe('summary translation helpers', () => {
  it('replaces summary text in order and leaves the original untouched', async () => {
    const { collectSummaryTexts, withTranslatedSummary, baseLanguage } = await import('./translate');
    const texts = collectSummaryTexts(result);
    expect(texts).toEqual(['A neural network recognises digits.', 'Layers build on each other.', 'Introduction', 'This is a 3.', 'pixels', 'Series preview']);

    const shown = withTranslatedSummary(result, texts.map((text) => `[hi] ${text}`), 'hi');
    expect(shown.summary.short[0]).toEqual({ text: '[hi] A neural network recognises digits.', start: 100 });
    expect(shown.summary.sections[0].title).toBe('[hi] Introduction');
    expect(shown.summary.sections[0].points[0]).toEqual({ text: '[hi] This is a 3.', start: 4.22 });
    expect(shown.summary.sections[0].keywords).toEqual(['[hi] pixels']);
    expect(shown.summary.sections[1].title).toBe('[hi] Series preview');
    expect(shown.captions.languageCode).toBe('hi');
    expect(shown.transcript).toBe(result.transcript);
    // The original is not modified.
    expect(result.summary.sections[0].title).toBe('Introduction');
    expect(result.captions.languageCode).toBe('en');
    expect(baseLanguage('en-US')).toBe('en');
  });
});
