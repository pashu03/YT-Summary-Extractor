import type { Cue, TranscriptResult } from '@/types/api';
import { formatClock, formatDuration, formatSubtitleTime } from './format';

const RULE = '─'.repeat(60);

function header(result: TranscriptResult, kind: string): string[] {
  const { video, captions } = result;
  return [
    video.title,
    RULE,
    `Channel:   ${video.author}`,
    `Video:     ${video.url}`,
    ...(video.durationSeconds > 0 ? [`Duration:  ${formatDuration(video.durationSeconds)}`] : []),
    `Captions:  ${captions.name}${captions.isAutoGenerated && !/auto/i.test(captions.name) ? ' (auto-generated)' : ''}`,
    `Document:  ${kind}`,
    RULE,
    '',
  ];
}

/** Readable transcript as plain text, grouped into paragraphs under their section headings. */
export function toTranscriptText(result: TranscriptResult, options: { timestamps: boolean }): string {
  const lines = header(result, 'Transcript');
  const sections = result.summary.sections;
  let currentSection = -1;

  for (const paragraph of result.transcript.paragraphs) {
    if (sections.length > 1 && paragraph.sectionIndex !== currentSection) {
      currentSection = paragraph.sectionIndex;
      const section = sections[currentSection];
      if (section) lines.push(`## ${section.title} (${formatClock(section.start)})`, '');
    }
    lines.push(options.timestamps ? `[${formatClock(paragraph.start)}] ${paragraph.text}` : paragraph.text, '');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

/** Summary, takeaways, per-section points and keywords as plain text. */
export function toSummaryText(result: TranscriptResult): string {
  const { summary, keywords } = result;
  const lines = header(result, 'Summary');
  const bullet = (text: string, start: number) => `  • [${formatClock(start)}] ${text}`;

  if (summary.short.length > 0) {
    lines.push('SUMMARY', '', summary.short.map((s) => s.text).join(' '), '');
  }
  if (summary.takeaways.length > 0) {
    lines.push('KEY TAKEAWAYS', '', ...summary.takeaways.map((t) => bullet(t.text, t.start)), '');
  }
  const sections = summary.sections.filter((section) => section.points.length > 0);
  if (sections.length > 0) {
    lines.push('DETAILED SUMMARY', '');
    for (const section of sections) {
      lines.push(`${section.title} (${formatClock(section.start)} – ${formatClock(section.end)})`);
      lines.push(...section.points.map((p) => bullet(p.text, p.start)), '');
    }
  }
  if (keywords.length > 0) {
    lines.push('KEYWORDS', '', keywords.map((k) => k.term).join(', '), '');
  }
  lines.push(RULE, 'Extractive summary: every sentence is quoted from the video (TF-IDF + TextRank).');
  return `${lines.join('\n')}\n`;
}

/** SubRip (.srt): numbered cues with comma-separated milliseconds. */
export function toSrt(cues: Cue[]): string {
  return cues
    .map((cue, index) => {
      const range = `${formatSubtitleTime(cue.start, ',')} --> ${formatSubtitleTime(cue.end, ',')}`;
      return `${index + 1}\n${range}\n${cue.text}\n`;
    })
    .join('\n');
}

/** WebVTT cue text may not contain "-->" or raw "&" / "<". */
const escapeVtt = (text: string) => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/-->/g, '--&gt;');

/** WebVTT (.vtt): the format browsers and HTML5 <track> elements use. */
export function toVtt(cues: Cue[]): string {
  const body = cues
    .map((cue) => `${formatSubtitleTime(cue.start, '.')} --> ${formatSubtitleTime(cue.end, '.')}\n${escapeVtt(cue.text)}\n`)
    .join('\n');
  return `WEBVTT\n\n${body}`;
}

/** Caption cues as plain text, one line per cue. */
export function toCueText(cues: Cue[], options: { timestamps: boolean }): string {
  return cues.map((cue) => (options.timestamps ? `[${formatClock(cue.start)}] ${cue.text}` : cue.text)).join('\n');
}

/** Turn a video title into a filename that is valid on Windows, macOS and Linux. */
export function safeFilename(title: string, suffix: string, extension: string): string {
  const base =
    title
      // Characters that are reserved in filenames, plus control characters.
      .replace(/[\\/:*?"<>|]+/g, ' ')
      .replace(/\p{Cc}+/gu, ' ')
      .replace(/\s+/g, ' ')
      .trim()
      .replace(/[. ]+$/, '')
      .slice(0, 80) || 'youtube-video';
  return `${base} - ${suffix}.${extension}`;
}

/** Save text or binary content as a file, entirely in the browser. */
export function downloadFile(filename: string, content: string | Blob, mimeType = 'text/plain;charset=utf-8'): void {
  // A leading byte-order mark makes Windows editors detect UTF-8 in plain-text files.
  const prefix = mimeType.startsWith('text/plain') ? String.fromCharCode(0xfeff) : '';
  const blob = content instanceof Blob ? content : new Blob([prefix, content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  link.rel = 'noopener';
  document.body.appendChild(link);
  link.click();
  link.remove();
  // Release the in-memory copy once the browser has started the download.
  setTimeout(() => URL.revokeObjectURL(url), 10_000);
}
