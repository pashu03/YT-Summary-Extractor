/**
 * Shapes returned by the API. Mirror of `backend/src/types.ts` — change both together.
 */

export interface VideoMeta {
  id: string;
  url: string;
  title: string;
  author: string;
  channelUrl: string | null;
  durationSeconds: number;
  thumbnailUrl: string;
  viewCount: number | null;
}

export interface CaptionTrackInfo {
  /** Stable identifier for the track (e.g. ".en" or "a.en"). */
  id: string;
  languageCode: string;
  name: string;
  isAutoGenerated: boolean;
}

export interface CaptionInfo extends CaptionTrackInfo {
  available: CaptionTrackInfo[];
}

/** One caption cue exactly as timed by YouTube, with cleaned text. */
export interface Cue {
  start: number;
  end: number;
  text: string;
}

/** A readable block of transcript text made of several sentences. */
export interface Paragraph {
  start: number;
  end: number;
  text: string;
  sectionIndex: number;
}

export interface TimedText {
  text: string;
  start: number;
}

export interface SectionSummary {
  index: number;
  title: string;
  start: number;
  end: number;
  /** "chapter" when the creator listed chapters in the description, otherwise detected. */
  source: 'chapter' | 'auto';
  keywords: string[];
  points: TimedText[];
  wordCount: number;
  /** Fraction of the transcript's words that fall in this section (0–1). */
  share: number;
}

export interface Keyword {
  term: string;
  /** Relevance normalised to 0–1 (top keyword = 1). */
  score: number;
  count: number;
  kind: 'word' | 'phrase';
}

export interface TranscriptStats {
  wordCount: number;
  sentenceCount: number;
  cueCount: number;
  sectionCount: number;
  readingMinutes: number;
  speakingRateWpm: number;
  summaryWordCount: number;
  /** Summary length as a fraction of the transcript length (0–1). */
  compression: number;
  /** True when the captions carry sentence punctuation. */
  punctuated: boolean;
  processingMs: number;
}

export interface TranscriptResult {
  video: VideoMeta;
  captions: CaptionInfo;
  transcript: {
    cues: Cue[];
    paragraphs: Paragraph[];
  };
  summary: {
    short: TimedText[];
    takeaways: TimedText[];
    sections: SectionSummary[];
  };
  keywords: Keyword[];
  stats: TranscriptStats;
}

export type Stage = 'validate' | 'metadata' | 'captions' | 'transcript' | 'analysis' | 'summary' | 'done';

export interface ApiErrorBody {
  code: string;
  message: string;
  /** Extra context, e.g. the reason YouTube gave. */
  detail?: string;
  /** Present on LANGUAGE_UNAVAILABLE so the UI can offer alternatives. */
  availableLanguages?: CaptionTrackInfo[];
}

export type StreamEvent =
  | { type: 'progress'; stage: Stage; percent: number; message: string }
  | { type: 'video'; video: VideoMeta; available: CaptionTrackInfo[] }
  | { type: 'result'; result: TranscriptResult }
  | { type: 'error'; error: ApiErrorBody };
