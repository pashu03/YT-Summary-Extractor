'use client';

import { Captions, Clock, ExternalLink, Eye, Languages, Play, Undo2 } from 'lucide-react';
import { useState } from 'react';
import { ListenButton } from '@/components/speech';
import { Badge } from '@/components/ui/badge';
import { Button } from '@/components/ui/button';
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from '@/components/ui/select';
import { formatClock, formatCompact } from '@/lib/format';
import type { CaptionTrackInfo, VideoMeta } from '@/types/api';

interface VideoCardProps {
  video: VideoMeta;
  available: CaptionTrackInfo[];
  /** The caption track in use, once known. */
  activeTrack?: CaptionTrackInfo;
  /** Disables the language picker while a request is running. */
  busy: boolean;
  onChangeLanguage: (trackId: string) => void;
}

export function VideoCard({ video, available, activeTrack, busy, onChangeLanguage }: VideoCardProps) {
  // The official embedded player is only loaded when the visitor asks for it.
  const [playing, setPlaying] = useState(false);
  // The track that was showing before "View in English" was pressed, so one click goes back.
  const [original, setOriginal] = useState<CaptionTrackInfo | null>(null);

  const isEnglish = (track: CaptionTrackInfo) => track.languageCode.toLowerCase().split('-')[0] === 'en';
  // Captions written by the creator are preferred over auto-generated ones.
  const english = available.find((t) => isEnglish(t) && !t.isAutoGenerated) ?? available.find(isEnglish);
  const showingEnglish = activeTrack ? isEnglish(activeTrack) : false;
  const canGoBack = showingEnglish && original !== null && available.some((t) => t.id === original.id);

  return (
    <section aria-label="Video" className="overflow-hidden rounded-2xl bg-white shadow-sm ring-1 ring-border">
      <div className="grid gap-0 md:grid-cols-[minmax(0,320px)_1fr]">
        <div className="relative aspect-video bg-slate-900 md:h-full md:min-h-[180px]">
          {playing ? (
            <iframe
              className="absolute inset-0 size-full"
              src={`https://www.youtube-nocookie.com/embed/${video.id}?autoplay=1&rel=0`}
              title={video.title}
              allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share"
              referrerPolicy="strict-origin-when-cross-origin"
              allowFullScreen
            />
          ) : (
            <button
              type="button"
              onClick={() => setPlaying(true)}
              className="group absolute inset-0 size-full focus-visible:ring-4 focus-visible:ring-ring focus-visible:outline-none focus-visible:ring-inset"
              aria-label={`Play video: ${video.title}`}
            >
              {/* A plain <img> keeps thumbnails loading straight from YouTube's CDN with no image proxy to configure. */}
              {/* eslint-disable-next-line @next/next/no-img-element */}
              <img src={video.thumbnailUrl} alt="" className="absolute inset-0 size-full object-cover" referrerPolicy="no-referrer" />
              <span className="absolute inset-0 bg-linear-to-t from-slate-950/50 via-transparent to-transparent" aria-hidden />
              <span className="absolute top-1/2 left-1/2 flex size-14 -translate-x-1/2 -translate-y-1/2 items-center justify-center rounded-full bg-white/95 text-primary shadow-lg transition-transform group-hover:scale-110">
                <Play className="size-6 translate-x-0.5 fill-current" aria-hidden />
              </span>
              {video.durationSeconds > 0 && (
                <span className="absolute right-2 bottom-2 rounded-md bg-slate-950/85 px-1.5 py-0.5 font-mono text-xs font-medium text-white">
                  {formatClock(video.durationSeconds)}
                </span>
              )}
            </button>
          )}
        </div>

        <div className="flex min-w-0 flex-col gap-3 p-5 sm:p-6">
          <div className="min-w-0">
            <div className="flex items-start justify-between gap-3">
              <h2 className="text-lg leading-snug font-semibold text-balance text-foreground sm:text-xl">{video.title}</h2>
              <ListenButton id="video-details" label="the video title" lang={activeTrack?.languageCode} text={`${video.title}. By ${video.author}.`} />
            </div>
            <p className="mt-1 text-sm text-muted-foreground">
              {video.channelUrl ? (
                <a href={video.channelUrl} target="_blank" rel="noopener noreferrer" className="font-medium text-foreground/80 underline-offset-4 hover:text-primary hover:underline">
                  {video.author}
                </a>
              ) : (
                <span className="font-medium text-foreground/80">{video.author}</span>
              )}
            </p>
          </div>

          <div className="flex flex-wrap gap-2">
            {video.durationSeconds > 0 && (
              <Badge variant="secondary" className="h-6 gap-1.5 px-2.5">
                <Clock aria-hidden /> {formatClock(video.durationSeconds)}
              </Badge>
            )}
            {video.viewCount !== null && (
              <Badge variant="secondary" className="h-6 gap-1.5 px-2.5">
                <Eye aria-hidden /> {formatCompact(video.viewCount)} views
              </Badge>
            )}
            {activeTrack && (
              <Badge variant="secondary" className="h-6 gap-1.5 px-2.5">
                <Captions aria-hidden /> {activeTrack.isAutoGenerated ? 'Auto-generated captions' : 'Creator captions'}
              </Badge>
            )}
          </div>

          <div className="mt-auto flex flex-wrap items-center gap-2 pt-1">
            {available.length > 0 && (
              <Select value={activeTrack?.id ?? ''} onValueChange={onChangeLanguage} disabled={busy || available.length < 2}>
                <SelectTrigger size="sm" className="max-w-full min-w-44" aria-label="Caption language">
                  {/* Icon and label stay together at the left; the chevron sits at the right. */}
                  <span className="flex min-w-0 items-center gap-1.5">
                    <Languages className="text-muted-foreground" aria-hidden />
                    <SelectValue placeholder="Caption language" />
                  </span>
                </SelectTrigger>
                <SelectContent position="popper" className="max-h-72">
                  {available.map((track) => (
                    <SelectItem key={track.id} value={track.id}>
                      {track.name}
                    </SelectItem>
                  ))}
                </SelectContent>
              </Select>
            )}
            {activeTrack && !showingEnglish && english && (
              <Button
                type="button"
                size="sm"
                disabled={busy}
                onClick={() => {
                  setOriginal(activeTrack);
                  onChangeLanguage(english.id);
                }}
                title="Switch the transcript, summary, topics and keywords to English"
              >
                <Languages /> View in English
              </Button>
            )}
            {canGoBack && original && (
              <Button type="button" variant="outline" size="sm" disabled={busy} onClick={() => onChangeLanguage(original.id)}>
                <Undo2 /> Back to {original.name.replace(/s*(auto-generated)/i, '')}
              </Button>
            )}
            <Button asChild variant="outline" size="sm">
              <a href={video.url} target="_blank" rel="noopener noreferrer">
                <ExternalLink /> Open on YouTube
              </a>
            </Button>
          </div>
          {activeTrack && !showingEnglish && !english && (
            <p className="text-xs text-muted-foreground">
              This video has no English captions, so it can&apos;t be shown in English here. YouTube does not allow its automatic caption
              translation to be used by other sites.
            </p>
          )}
        </div>
      </div>
    </section>
  );
}
