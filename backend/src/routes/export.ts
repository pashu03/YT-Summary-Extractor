import { Router, type Request, type Response } from 'express';
import { z } from 'zod';
import { AppError } from '../errors.js';
import { renderReport } from '../pdf/report.js';

const seconds = z.number().finite().min(0).max(1_000_000);
const timedLine = z.object({ text: z.string().max(8_000), start: seconds });

/** Everything the PDF needs is sent by the browser; the server keeps no copy of earlier results. */
const exportSchema = z.object({
  video: z.object({
    id: z.string().regex(/^[A-Za-z0-9_-]{11}$/),
    title: z.string().max(500),
    author: z.string().max(300),
    durationSeconds: seconds,
  }),
  language: z.object({ name: z.string().max(120), isAutoGenerated: z.boolean() }),
  include: z
    .object({ summary: z.boolean(), transcript: z.boolean(), timestamps: z.boolean() })
    .refine((value) => value.summary || value.transcript, 'Choose the summary, the transcript, or both.'),
  summary: z.object({
    short: z.array(timedLine).max(20),
    takeaways: z.array(timedLine).max(30),
    sections: z
      .array(z.object({ title: z.string().max(300), start: seconds, end: seconds, points: z.array(timedLine).max(20) }))
      .max(80),
  }),
  keywords: z.array(z.string().max(120)).max(60),
  paragraphs: z
    .array(z.object({ start: seconds, text: z.string().max(40_000), sectionIndex: z.number().int().min(0) }))
    .max(30_000),
  stats: z.object({ wordCount: z.number().finite().min(0), readingMinutes: z.number().finite().min(0) }).partial().optional(),
});

/** A filename that is safe in a Content-Disposition header on every platform. */
function buildFilename(title: string, suffix: string): { ascii: string; encoded: string } {
  const base = title.replace(/[\\/:*?"<>|\u0000-\u001f]+/g, ' ').replace(/\s+/g, ' ').trim().slice(0, 80) || 'transcript';
  const full = `${base} - ${suffix}.pdf`;
  const ascii = full.replace(/[^\x20-\x7e]/g, '_').replace(/["\\]/g, '_');
  return { ascii, encoded: encodeURIComponent(full) };
}

export const exportRouter = Router();

/** POST /api/export/pdf — returns the report as a PDF download. */
exportRouter.post('/pdf', async (req: Request, res: Response) => {
  const parsed = exportSchema.safeParse(req.body);
  if (!parsed.success) {
    const issue = parsed.error.issues[0];
    throw new AppError('INVALID_REQUEST', {
      message: 'The export request was not valid.',
      detail: issue ? `${issue.path.join('.')}: ${issue.message}` : undefined,
    });
  }

  const input = parsed.data;
  const pdf = await renderReport(input);
  const suffix = input.include.summary && input.include.transcript ? 'summary and transcript' : input.include.summary ? 'summary' : 'transcript';
  const { ascii, encoded } = buildFilename(input.video.title, suffix);

  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader('Content-Length', String(pdf.length));
  res.setHeader('Content-Disposition', `attachment; filename="${ascii}"; filename*=UTF-8''${encoded}`);
  res.end(pdf);
});
