import PDFDocument from 'pdfkit';
import { AppError } from '../errors.js';
import { getFaces, toRuns, unsupportedLetterShare, type Weight } from './fonts.js';

export interface TimedLine {
  text: string;
  start: number;
}

export interface ReportInput {
  video: { id: string; title: string; author: string; durationSeconds: number };
  language: { name: string; isAutoGenerated: boolean };
  include: { summary: boolean; transcript: boolean; timestamps: boolean };
  summary: {
    short: TimedLine[];
    takeaways: TimedLine[];
    sections: { title: string; start: number; end: number; points: TimedLine[] }[];
  };
  keywords: string[];
  paragraphs: { start: number; text: string; sectionIndex: number }[];
  stats?: { wordCount?: number; readingMinutes?: number };
}

const COLOR = {
  navy: '#0B2A5B',
  blue: '#1D4ED8',
  text: '#1F2937',
  muted: '#64748B',
  rule: '#DBEAFE',
  tint: '#EFF6FF',
};

const PAGE = { size: 'A4' as const, margin: 54 };
const TIMESTAMP_COLUMN = 50;

export function formatClock(totalSeconds: number): string {
  const seconds = Math.max(0, Math.floor(totalSeconds));
  const h = Math.floor(seconds / 3600);
  const m = Math.floor((seconds % 3600) / 60);
  const s = seconds % 60;
  const pad = (n: number) => String(n).padStart(2, '0');
  return h > 0 ? `${h}:${pad(m)}:${pad(s)}` : `${m}:${pad(s)}`;
}

/** Above this share of undrawable letters the PDF would be mostly blank, so the export is refused. */
const MAX_UNSUPPORTED_SHARE = 0.03;

/**
 * Render the summary and/or transcript as a PDF and return it as a buffer.
 * The document is built entirely in memory; nothing is written to disk.
 */
export function renderReport(input: ReportInput): Promise<Buffer> {
  const { video, include } = input;
  const videoUrl = `https://www.youtube.com/watch?v=${video.id}`;
  const linkAt = (seconds: number) => `${videoUrl}&t=${Math.max(0, Math.floor(seconds))}s`;

  const sample = [
    video.title,
    ...(include.summary ? input.summary.short.map((s) => s.text) : []),
    ...(include.transcript ? input.paragraphs.map((p) => p.text) : []),
  ].join(' ');
  if (unsupportedLetterShare(sample) > MAX_UNSUPPORTED_SHARE) throw new AppError('UNSUPPORTED_SCRIPT');

  const doc = new PDFDocument({
    size: PAGE.size,
    margin: PAGE.margin,
    bufferPages: true,
    info: {
      Title: video.title,
      Author: video.author,
      Subject: 'YouTube transcript and extractive summary',
      Creator: 'YouTube Transcript & Summary Extractor',
    },
  });
  const faces = getFaces();
  for (const face of [...faces.regular, ...faces.bold]) doc.registerFont(face.name, face.data);

  const chunks: Buffer[] = [];
  const finished = new Promise<Buffer>((resolve, reject) => {
    doc.on('data', (chunk: Buffer) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
  });

  const left = PAGE.margin;
  const width = doc.page.width - PAGE.margin * 2;
  const bottom = () => doc.page.height - PAGE.margin - 18;

  interface WriteOptions {
    size: number;
    weight?: Weight;
    color?: string;
    x?: number;
    width?: number;
    lineGap?: number;
    link?: string;
    align?: 'left' | 'justify';
  }

  /** Draw text that may mix scripts, switching fonts between runs on the same line. */
  const write = (text: string, options: WriteOptions) => {
    const runs = toRuns(text, options.weight ?? 'regular');
    if (runs.length === 0) return;
    const x = options.x ?? left;
    doc.fontSize(options.size).fillColor(options.color ?? COLOR.text);
    runs.forEach((run, index) => {
      const textOptions = {
        width: options.width ?? width - (x - left),
        lineGap: options.lineGap ?? 2,
        align: options.align ?? 'left',
        continued: index < runs.length - 1,
        link: options.link ?? null,
      } as PDFKit.Mixins.TextOptions;
      doc.font(run.font);
      if (index === 0) doc.text(run.text, x, doc.y, textOptions);
      else doc.text(run.text, textOptions);
    });
  };

  /** Height the text would take, so a block can be moved to the next page instead of splitting badly. */
  const measure = (text: string, size: number, weight: Weight, measureWidth: number) => {
    const runs = toRuns(text, weight);
    doc.font(runs[0]?.font ?? faces[weight][0].name).fontSize(size);
    return doc.heightOfString(runs.map((run) => run.text).join(''), { width: measureWidth, lineGap: 2 });
  };

  const ensureSpace = (height: number) => {
    if (doc.y + height > bottom()) doc.addPage();
  };

  const sectionHeading = (title: string) => {
    ensureSpace(64);
    doc.moveDown(0.8);
    write(title, { size: 14, weight: 'bold', color: COLOR.navy });
    const y = doc.y + 3;
    doc.moveTo(left, y).lineTo(left + width, y).lineWidth(1.5).strokeColor(COLOR.rule).stroke();
    doc.y = y + 10;
  };

  /** A line of text with its timestamp in a left-hand column, linked to that moment in the video. */
  const timedRow = (line: TimedLine, options: { size?: number; bullet?: boolean } = {}) => {
    const size = options.size ?? 10.5;
    const indent = include.timestamps ? TIMESTAMP_COLUMN : options.bullet ? 12 : 0;
    const textWidth = width - indent;
    // Keep short rows whole; long paragraphs are allowed to flow across pages.
    ensureSpace(Math.min(measure(line.text, size, 'regular', textWidth), 60));
    const top = doc.y;
    if (include.timestamps) {
      write(formatClock(line.start), { size: size - 1.5, weight: 'bold', color: COLOR.blue, width: indent - 8, link: linkAt(line.start) });
    } else if (options.bullet) {
      write('•', { size, color: COLOR.blue, width: indent });
    }
    doc.y = top;
    write(line.text, { size, x: left + indent, width: textWidth });
    doc.moveDown(0.45);
  };

  /* ---------------- Header ---------------- */
  write('YOUTUBE TRANSCRIPT & SUMMARY', { size: 8.5, weight: 'bold', color: COLOR.blue });
  doc.moveDown(0.35);
  write(video.title, { size: 19, weight: 'bold', color: COLOR.navy, lineGap: 3 });
  doc.moveDown(0.3);

  const facts = [
    video.author,
    video.durationSeconds > 0 ? formatClock(video.durationSeconds) : null,
    `${input.language.name}${input.language.isAutoGenerated && !/auto/i.test(input.language.name) ? ' (auto-generated)' : ''}`,
    input.stats?.wordCount ? `${input.stats.wordCount.toLocaleString('en-US')} words` : null,
    input.stats?.readingMinutes ? `${Math.max(1, Math.round(input.stats.readingMinutes))} min read` : null,
  ].filter(Boolean);
  write(facts.join('  ·  '), { size: 9.5, color: COLOR.muted });
  doc.moveDown(0.15);
  write(videoUrl, { size: 9.5, color: COLOR.blue, link: videoUrl });
  doc.moveDown(0.6);

  /* ---------------- Summary ---------------- */
  if (include.summary) {
    if (input.summary.short.length > 0) {
      sectionHeading('Summary');
      const text = input.summary.short.map((s) => s.text).join(' ');
      const height = measure(text, 10.5, 'regular', width - 24) + 20;
      ensureSpace(height);
      const top = doc.y;
      doc.roundedRect(left, top, width, height, 6).fill(COLOR.tint);
      doc.y = top + 10;
      write(text, { size: 10.5, x: left + 12, width: width - 24 });
      doc.y = top + height + 6;
    }

    if (input.summary.takeaways.length > 0) {
      sectionHeading('Key takeaways');
      for (const line of input.summary.takeaways) timedRow(line, { bullet: true });
    }

    const sections = input.summary.sections.filter((section) => section.points.length > 0);
    if (sections.length > 0) {
      sectionHeading('Detailed summary');
      for (const section of sections) {
        ensureSpace(70);
        const range = `${formatClock(section.start)} – ${formatClock(section.end)}`;
        write(section.title, { size: 11.5, weight: 'bold', color: COLOR.navy });
        write(range, { size: 8.5, color: COLOR.muted, link: linkAt(section.start) });
        doc.moveDown(0.35);
        for (const point of section.points) timedRow(point, { bullet: true });
        doc.moveDown(0.35);
      }
    }

    if (input.keywords.length > 0) {
      sectionHeading('Keywords');
      write(input.keywords.join('  ·  '), { size: 10, color: COLOR.text, lineGap: 4 });
      doc.moveDown(0.5);
    }
  }

  /* ---------------- Transcript ---------------- */
  if (include.transcript && input.paragraphs.length > 0) {
    if (include.summary) doc.addPage();
    sectionHeading('Full transcript');
    let currentSection = -1;
    for (const paragraph of input.paragraphs) {
      const section = input.summary.sections[paragraph.sectionIndex];
      if (paragraph.sectionIndex !== currentSection && section && input.summary.sections.length > 1) {
        currentSection = paragraph.sectionIndex;
        ensureSpace(60);
        doc.moveDown(0.4);
        write(section.title, { size: 11, weight: 'bold', color: COLOR.navy });
        doc.moveDown(0.3);
      }
      timedRow({ text: paragraph.text, start: paragraph.start }, { size: 10 });
    }
  }

  /* ---------------- Footer on every page ---------------- */
  const range = doc.bufferedPageRange();
  for (let i = 0; i < range.count; i++) {
    doc.switchToPage(range.start + i);
    // Drawing inside the bottom margin would otherwise trigger an automatic page break.
    const margin = doc.page.margins.bottom;
    doc.page.margins.bottom = 0;
    const y = doc.page.height - margin + 6;
    doc.font(faces.regular[0].name).fontSize(8).fillColor(COLOR.muted);
    doc.text('Extractive summary generated with TF-IDF and TextRank — every sentence is quoted from the video.', left, y, {
      width: width - 70,
      lineBreak: false,
    });
    doc.text(`Page ${i + 1} of ${range.count}`, left, y, { width, align: 'right', lineBreak: false });
    doc.page.margins.bottom = margin;
  }

  doc.end();
  return finished;
}
