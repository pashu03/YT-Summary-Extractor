import { config } from '../config.js';
import { AppError } from '../errors.js';
import type { CaptionTrackInfo } from '../types.js';
import { cleanCaptionText, type RawCue } from './captions.js';
import { request } from './http.js';

/**
 * Captions through the Supadata transcript API (https://supadata.ai), for
 * hosts that YouTube refuses to serve directly. Only the video's existing
 * captions are requested (`mode=native`): no speech-to-text, no AI. The
 * API key stays on the server; nothing is cached or stored.
 */

const API = 'https://api.supadata.ai/v1/transcript';
const POLL_INTERVAL_MS = 1_500;

interface Chunk {
  text?: string;
  offset?: number;
  duration?: number;
}

interface TranscriptBody {
  content?: Chunk[] | string;
  lang?: string;
  availableLangs?: string[];
}

interface JobBody extends TranscriptBody {
  jobId?: string;
  status?: 'queued' | 'active' | 'completed' | 'failed';
  error?: ServiceError | null;
}

interface ServiceError {
  error?: string;
  message?: string;
  details?: string;
}

export interface ServiceTranscript {
  track: CaptionTrackInfo;
  available: CaptionTrackInfo[];
  cues: RawCue[];
}

const primary = (code: string) => code.toLowerCase().split(/[-_]/)[0];

const languageNames = new Intl.DisplayNames(['en'], { type: 'language' });
function languageName(code: string): string {
  try {
    return languageNames.of(code) ?? code;
  } catch {
    return code;
  }
}

function toTrack(code: string): CaptionTrackInfo {
  // The service does not say whether captions were made by the creator or by YouTube.
  return { id: code, languageCode: code, name: languageName(code), isAutoGenerated: false, kindUnknown: true };
}

/** Track ids from YouTube itself look like ".en" or "a.hi"; the service only needs the language. */
function requestedLanguage(requested: string | undefined): string | undefined {
  if (!requested) return undefined;
  const code = requested.replace(/^a?\./, '').trim();
  return /^[a-z]{2,3}([-_][a-z0-9]{2,8})*$/i.test(code) ? code : undefined;
}

function parseJson<T>(body: string): T | null {
  try {
    return JSON.parse(body) as T;
  } catch {
    return null;
  }
}

/** Server-side note of what the service said; never includes the API key or transcript. */
function logService(status: number, info: ServiceError | null) {
  const code = info?.error ?? 'unknown';
  const message = (info?.message || info?.details || '').slice(0, 200);
  console.warn(`[supadata] HTTP ${status} ${code}${message ? ` "${message}"` : ''}`);
}

/** Map the service's answer onto the API's existing error codes and wording. */
function toAppError(status: number, info: ServiceError | null): AppError {
  logService(status, info);
  const code = info?.error;
  if (status === 206 || code === 'transcript-unavailable') return new AppError('NO_CAPTIONS');
  if (status === 404 || code === 'not-found') return new AppError('VIDEO_UNAVAILABLE');
  if (status === 403 || code === 'forbidden') return new AppError('RESTRICTED');
  if (status === 401 || code === 'unauthorized') {
    return new AppError('EXTRACTION_FAILED', {
      message: "The transcript service isn't set up correctly on this server, so captions can't be retrieved right now.",
    });
  }
  if (status === 402 || status === 429 || code === 'upgrade-required' || code === 'limit-exceeded') {
    return new AppError('EXTRACTION_FAILED', {
      message: "This server has used up its transcript allowance for now. Please try again later.",
    });
  }
  return new AppError('EXTRACTION_FAILED');
}

function toCues(content: TranscriptBody['content']): RawCue[] {
  if (!Array.isArray(content)) return [];
  const cues: RawCue[] = [];
  for (const chunk of content) {
    const text = cleanCaptionText(chunk.text ?? '');
    const start = Number(chunk.offset);
    const duration = Number(chunk.duration);
    if (!text || !Number.isFinite(start) || start < 0) continue;
    cues.push({ start: start / 1000, duration: Number.isFinite(duration) && duration > 0 ? duration / 1000 : 0, text });
  }
  return cues.sort((a, b) => a.start - b.start);
}

function sleep(ms: number, signal?: AbortSignal) {
  return new Promise<void>((resolve, reject) => {
    const timer = setTimeout(resolve, ms);
    signal?.addEventListener(
      'abort',
      () => {
        clearTimeout(timer);
        reject(new AppError('CANCELLED'));
      },
      { once: true },
    );
  });
}

export function isServiceConfigured(): boolean {
  return config.supadataApiKey.length > 0;
}

export async function fetchServiceTranscript(
  videoId: string,
  requested: string | undefined,
  signal?: AbortSignal,
): Promise<ServiceTranscript> {
  if (!isServiceConfigured()) {
    console.warn('[supadata] TRANSCRIPT_PROVIDER needs SUPADATA_API_KEY, which is not set');
    throw new AppError('EXTRACTION_FAILED', {
      message: "The transcript service isn't set up on this server, so captions can't be retrieved right now.",
    });
  }

  const deadline = Date.now() + config.transcriptServiceTimeoutMs;
  const remaining = () => deadline - Date.now();
  const headers = { 'x-api-key': config.supadataApiKey, Accept: 'application/json' };
  const lang = requestedLanguage(requested);

  const params = new URLSearchParams({ url: `https://www.youtube.com/watch?v=${videoId}`, mode: 'native', text: 'false' });
  if (lang) params.set('lang', lang);

  let { status, body } = await request(`${API}?${params}`, { headers, signal, timeoutMs: Math.min(remaining(), 30_000) });
  let data = parseJson<JobBody>(body);

  // Large videos are processed as a job: poll until it finishes or the time budget runs out.
  if (status === 202 && data?.jobId) {
    const jobUrl = `${API}/${encodeURIComponent(data.jobId)}`;
    for (;;) {
      if (remaining() <= POLL_INTERVAL_MS) {
        console.warn('[supadata] transcript job did not finish in time');
        throw new AppError('TIMEOUT');
      }
      await sleep(POLL_INTERVAL_MS, signal);
      ({ status, body } = await request(jobUrl, { headers, signal, timeoutMs: Math.min(remaining(), 15_000) }));
      data = parseJson<JobBody>(body);
      if (status !== 200) break;
      if (data?.status === 'failed') throw toAppError(status, data.error ?? null);
      if (data?.status === 'completed') break;
    }
  }

  if (status !== 200 || !data) throw toAppError(status, parseJson<ServiceError>(body));

  const cues = toCues(data.content);
  if (cues.length === 0) throw new AppError('EMPTY_TRANSCRIPT');

  const returned = data.lang || lang || 'und';
  const codes = [...new Set([returned, ...(data.availableLangs ?? [])].filter(Boolean))];
  const available = codes.map(toTrack);

  // The service falls back to another language when the requested one is missing; say so instead.
  if (lang && primary(returned) !== primary(lang)) {
    throw new AppError('LANGUAGE_UNAVAILABLE', { availableLanguages: available });
  }

  return { track: toTrack(returned), available, cues };
}
