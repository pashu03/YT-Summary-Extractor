import type { AddressInfo } from 'node:net';
import type { Server } from 'node:http';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { createApp } from '../src/app.js';
import { toRuns, unsupportedLetterShare } from '../src/pdf/fonts.js';
import { formatClock, renderReport, type ReportInput } from '../src/pdf/report.js';

let server: Server;
let base: string;

beforeAll(async () => {
  server = createApp().listen(0);
  await new Promise<void>((resolve) => server.once('listening', resolve));
  base = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
});

afterAll(async () => {
  await new Promise<void>((resolve) => server.close(() => resolve()));
});

const post = (path: string, body: unknown, headers: Record<string, string> = {}) =>
  fetch(`${base}${path}`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', ...headers },
    body: typeof body === 'string' ? body : JSON.stringify(body),
  });

const report: ReportInput = {
  video: { id: 'aircAruvnKk', title: 'But what is a neural network? | Chapter 1: "Deep" learning', author: '3Blue1Brown', durationSeconds: 1120 },
  language: { name: 'English', isAutoGenerated: false },
  include: { summary: true, transcript: true, timestamps: true },
  summary: {
    short: [{ text: 'A neural network learns to recognise handwritten digits.', start: 100 }],
    takeaways: [{ text: 'Activations in one layer determine the next layer.', start: 273 }],
    sections: [
      { title: 'Introduction', start: 0, end: 67, points: [{ text: 'This is a three.', start: 4 }] },
      { title: 'Layers', start: 67, end: 1120, points: [{ text: 'Layers break the problem into pieces.', start: 331 }] },
    ],
  },
  keywords: ['neural network', 'layer', 'weights'],
  paragraphs: [
    { start: 4, text: 'This is a three. It is sloppily written and rendered at a low resolution.', sectionIndex: 0 },
    { start: 67, text: 'Layers break the problem into pieces. Each neuron holds a number.', sectionIndex: 1 },
  ],
  stats: { wordCount: 3357, readingMinutes: 14.6 },
};

describe('HTTP API', () => {
  it('reports health', async () => {
    const res = await fetch(`${base}/api/health`);
    expect(res.status).toBe(200);
    expect(await res.json()).toMatchObject({ status: 'ok' });
    expect(res.headers.get('cache-control')).toBe('no-store');
    expect(res.headers.get('x-powered-by')).toBeNull();
  });

  it('rejects an invalid link with a 400 and a readable message', async () => {
    const res = await post('/api/transcript', { url: 'https://example.com/video' });
    expect(res.status).toBe(400);
    const body = await res.json();
    expect(body.error.code).toBe('INVALID_URL');
    expect(body.error.message).toMatch(/YouTube/);
  });

  it('rejects an invalid link before streaming starts', async () => {
    const res = await post('/api/transcript', { url: 'nope' }, { Accept: 'application/x-ndjson' });
    expect(res.status).toBe(400);
    expect(res.headers.get('content-type')).toContain('application/json');
  });

  it('rejects a missing or malformed body', async () => {
    expect((await post('/api/transcript', {})).status).toBe(400);
    const malformed = await post('/api/transcript', '{"url": ');
    expect(malformed.status).toBe(400);
    expect((await malformed.json()).error.code).toBe('INVALID_REQUEST');
  });

  it('returns 404 for unknown endpoints', async () => {
    const res = await fetch(`${base}/api/nothing-here`);
    expect(res.status).toBe(404);
    expect((await res.json()).error.code).toBe('NOT_FOUND');
  });

  it('answers CORS preflight for an allowed origin only', async () => {
    const allowed = await fetch(`${base}/api/transcript`, {
      method: 'OPTIONS',
      headers: { Origin: 'http://localhost:3000', 'Access-Control-Request-Method': 'POST' },
    });
    expect(allowed.headers.get('access-control-allow-origin')).toBe('http://localhost:3000');

    const denied = await fetch(`${base}/api/transcript`, {
      method: 'OPTIONS',
      headers: { Origin: 'https://evil.example', 'Access-Control-Request-Method': 'POST' },
    });
    expect(denied.headers.get('access-control-allow-origin')).toBeNull();
  });

  it('returns a PDF download with a safe filename', async () => {
    const res = await post('/api/export/pdf', report);
    expect(res.status).toBe(200);
    expect(res.headers.get('content-type')).toBe('application/pdf');
    const disposition = res.headers.get('content-disposition')!;
    // Characters that are illegal in filenames (? | : ") are removed from the title.
    expect(disposition).toContain('attachment; filename="But what is a neural network Chapter 1 Deep learning - summary and transcript.pdf"');
    expect(disposition).toContain("filename*=UTF-8''But%20what%20is");
    const bytes = Buffer.from(await res.arrayBuffer());
    expect(bytes.subarray(0, 5).toString()).toBe('%PDF-');
    expect(bytes.length).toBeGreaterThan(5000);
  });

  it('validates PDF export requests', async () => {
    const nothingSelected = await post('/api/export/pdf', { ...report, include: { summary: false, transcript: false, timestamps: true } });
    expect(nothingSelected.status).toBe(400);
    const badId = await post('/api/export/pdf', { ...report, video: { ...report.video, id: '../../etc' } });
    expect(badId.status).toBe(400);
    expect((await badId.json()).error.code).toBe('INVALID_REQUEST');
  });

  it('explains when a transcript uses a script the PDF fonts cannot draw', async () => {
    const res = await post('/api/export/pdf', {
      ...report,
      paragraphs: [{ start: 0, text: 'ニューラルネットワークは手書きの数字を認識することを学習します。', sectionIndex: 0 }],
    });
    expect(res.status).toBe(422);
    expect((await res.json()).error.code).toBe('UNSUPPORTED_SCRIPT');
  });
});

describe('PDF rendering', () => {
  it('formats clock times', () => {
    expect(formatClock(0)).toBe('0:00');
    expect(formatClock(75.9)).toBe('1:15');
    expect(formatClock(3725)).toBe('1:02:05');
  });

  it('switches font for Devanagari and drops characters no font can draw', () => {
    const runs = toRuns('Hello नमस्ते world 😀', 'regular');
    expect(runs.map((run) => run.font)).toEqual(['NotoSans-Regular', 'NotoSansDevanagari-Regular', 'NotoSans-Regular']);
    expect(runs.map((run) => run.text).join('')).toBe('Hello नमस्ते world ');
  });

  it('measures how much of a text is drawable', () => {
    expect(unsupportedLetterShare('Plain English, Ελληνικά, Русский, हिन्दी')).toBe(0);
    expect(unsupportedLetterShare('日本語のテキスト')).toBe(1);
  });

  it('renders summary-only and transcript-only documents', async () => {
    for (const include of [
      { summary: true, transcript: false, timestamps: false },
      { summary: false, transcript: true, timestamps: true },
    ]) {
      const pdf = await renderReport({ ...report, include });
      expect(pdf.subarray(0, 5).toString()).toBe('%PDF-');
    }
  });
});
