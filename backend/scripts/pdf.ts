/**
 * Render the PDF report for one video to a file, for checking the layout.
 *
 *   npx tsx scripts/pdf.ts <youtube-url-or-id> <output.pdf> [language]
 */
import { writeFileSync } from 'node:fs';
import { toAppError } from '../src/errors.js';
import { renderReport } from '../src/pdf/report.js';
import { runPipeline } from '../src/pipeline.js';

const [url, output, language] = process.argv.slice(2);
if (!url || !output) {
  console.error('Usage: npx tsx scripts/pdf.ts <youtube-url-or-id> <output.pdf> [language]');
  process.exit(1);
}

try {
  const result = await runPipeline({ url, language });
  const started = performance.now();
  const pdf = await renderReport({
    video: result.video,
    language: { name: result.captions.name, isAutoGenerated: result.captions.isAutoGenerated },
    include: { summary: true, transcript: true, timestamps: true },
    summary: result.summary,
    keywords: result.keywords.map((k) => k.term),
    paragraphs: result.transcript.paragraphs,
    stats: result.stats,
  });
  writeFileSync(output, pdf);
  console.log(`${result.video.title} [${result.captions.name}] → ${output} (${(pdf.length / 1024).toFixed(0)} KB, ${Math.round(performance.now() - started)} ms)`);
} catch (err) {
  const error = toAppError(err);
  console.error(`${error.code}: ${error.message}`);
  if (error.code === 'INTERNAL') console.error(err);
  process.exitCode = 1;
}
